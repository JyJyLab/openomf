// ---------------------------------------------------------------- Hangul (KOREAN.FNT)
// Tables are generated by korean/make_font.py from the Galmuri pixel fonts (SIL OFL 1.1).
// Glyph surfaces are created on first use and cached.
typedef struct ko_table {
    int w, h, bpr;
    uint32_t count;
    uint32_t *codepoints; // ascending
    uint8_t *bits;        // count * h * bpr, MSB = leftmost pixel
    surface **cache;
} ko_table;

static ko_table ko_small, ko_big;
static bool ko_loaded = false;

static void ko_free(ko_table *t) {
    if(t->cache != NULL) {
        for(uint32_t i = 0; i < t->count; i++) {
            if(t->cache[i] != NULL) {
                surface_free(t->cache[i]);
                omf_free(t->cache[i]);
            }
        }
    }
    omf_free(t->cache);
    omf_free(t->codepoints);
    omf_free(t->bits);
    memset(t, 0, sizeof(ko_table));
}

static bool ko_read_table(FILE *f, ko_table *small, ko_table *big) {
    uint8_t head[8];
    if(fread(head, 1, 8, f) != 8) {
        return false;
    }
    ko_table t;
    memset(&t, 0, sizeof(t));
    t.w = head[1];
    t.h = head[2];
    t.bpr = head[3];
    t.count = (uint32_t)head[4] | ((uint32_t)head[5] << 8) | ((uint32_t)head[6] << 16) | ((uint32_t)head[7] << 24);
    if(t.w == 0 || t.h == 0 || t.bpr == 0 || t.count == 0 || t.count > 65536) {
        return false;
    }
    t.codepoints = omf_calloc(t.count, sizeof(uint32_t));
    t.bits = omf_calloc((size_t)t.count * t.h * t.bpr, 1);
    t.cache = omf_calloc(t.count, sizeof(surface *));
    bool ok = true;
    for(uint32_t i = 0; i < t.count && ok; i++) {
        uint8_t b[4];
        ok = fread(b, 1, 4, f) == 4;
        t.codepoints[i] = (uint32_t)b[0] | ((uint32_t)b[1] << 8) | ((uint32_t)b[2] << 16) | ((uint32_t)b[3] << 24);
    }
    ok = ok && fread(t.bits, 1, (size_t)t.count * t.h * t.bpr, f) == (size_t)t.count * t.h * t.bpr;
    if(!ok) {
        ko_free(&t);
        return false;
    }
    ko_table *dst = head[0] == FONT_BIG ? big : small;
    ko_free(dst);
    *dst = t;
    return true;
}

static void ko_load(void) {
    path filename = get_resource_filename("KOREAN.FNT");
    FILE *f = fopen(path_c(&filename), "rb");
    if(f == NULL) {
        return;
    }
    char magic[8];
    uint8_t cnt[2];
    if(fread(magic, 1, 8, f) == 8 && memcmp(magic, "OMFKOFNT", 8) == 0 && fread(cnt, 1, 2, f) == 2) {
        int tables = cnt[0] | (cnt[1] << 8);
        bool ok = true;
        for(int i = 0; i < tables && ok; i++) {
            ok = ko_read_table(f, &ko_small, &ko_big);
        }
        ko_loaded = ok && ko_small.count > 0 && ko_big.count > 0;
        if(ko_loaded) {
            log_info("Loaded Korean font '%s'", path_c(&filename));
        } else {
            log_error("Korean font '%s' is corrupt", path_c(&filename));
            ko_free(&ko_small);
            ko_free(&ko_big);
        }
    }
    fclose(f);
}

static const surface *ko_glyph(ko_table *t, uint32_t cp) {
    if(t == NULL || t->count == 0) {
        return NULL;
    }
    uint32_t lo = 0, hi = t->count;
    while(lo < hi) {
        uint32_t mid = (lo + hi) / 2;
        if(t->codepoints[mid] < cp) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    if(lo >= t->count || t->codepoints[lo] != cp) {
        return NULL;
    }
    if(t->cache[lo] == NULL) {
        sd_vga_image img;
        sd_vga_image_create(&img, t->w, t->h);
        const uint8_t *g = t->bits + (size_t)lo * t->h * t->bpr;
        for(int y = 0; y < t->h; y++) {
            for(int x = 0; x < t->w; x++) {
                int set = (g[y * t->bpr + x / 8] >> (7 - x % 8)) & 1;
                img.data[y * t->w + x] = set ? 1 : 0;
            }
        }
        t->cache[lo] = omf_calloc(1, sizeof(surface));
        surface_create_from_vga(t->cache[lo], &img);
        surface_set_transparency(t->cache[lo], 0);
        sd_vga_image_free(&img);
    }
    return t->cache[lo];
}

void fonts_set_utf8(bool enabled) {
    utf8_mode = enabled;
}

bool fonts_get_utf8(void) {
    return utf8_mode;
}

// Decode one UTF-8 sequence. Returns the codepoint and its byte length, or 0 for invalid input.
static uint32_t utf8_decode(const unsigned char *s, size_t avail, size_t *len) {
    uint32_t c = s[0];
    size_t n = c >= 0xF0 ? 4 : c >= 0xE0 ? 3 : c >= 0xC0 ? 2 : 1;
    if(n == 1 || n > avail) {
        *len = 1;
        return 0;
    }
    uint32_t cp = c & (0x7F >> n);
    for(size_t i = 1; i < n; i++) {
        if((s[i] & 0xC0) != 0x80) {
            *len = 1;
            return 0;
        }
        cp = (cp << 6) | (s[i] & 0x3F);
    }
    *len = n;
    return cp;
}

const surface *font_get_glyph(const font *font, const char *s, size_t avail, size_t *len) {
    *len = 1;
    if(avail == 0) {
        return NULL;
    }
    const unsigned char c = (unsigned char)s[0];
    if(!utf8_mode || c < 0x80) {
        return font_get_surface(font, s[0]);
    }
    uint32_t cp = utf8_decode((const unsigned char *)s, avail, len);
    const surface *g = ko_glyph(font->ko, cp);
    if(g == NULL) {
        // Not in KOREAN.FNT: show '?' so the layout still advances
        g = font_get_surface(font, '?');
    }
    return g;
}

static void free_glyph(void *d) {
    surface *s = (surface *)d;
    surface_free(s);
}

void font_create(font *f) {
    memset(f, 0, sizeof(font));
    vector_create_with_size_cb(&f->surfaces, sizeof(surface), 233, free_glyph);
}

void font_free(font *font) {
    vector_free(&font->surfaces);
    font->ko = NULL;
}

static int text_char_to_glyph_index(char c) {
    int ic = (int)(unsigned char)c;
    return ic - FIRST_PRINTABLE_CHAR;
}

const surface *font_get_surface(const font *font, char ch) {
    int code = text_char_to_glyph_index(ch);
    if(code < 0) {
        return NULL;
    }
    return vector_get(&font->surfaces, code);
}

static int font_load(font *font, const path *filename, unsigned int size) {
    sd_vga_image img;
    sd_font sdfont;
    int pixsize;
    surface *sur;

    // Find vertical size
    switch(size) {
        case FONT_BIG:
            pixsize = 8;
            break;
        case FONT_SMALL:
            pixsize = 6;
            break;
        default:
            return 1;
    }

    // Open font file
    sd_font_create(&sdfont);
    if(sd_font_load(&sdfont, filename, pixsize)) {
        sd_font_free(&sdfont);
        return 2;
    }

    // Load into textures
    sd_vga_image_create(&img, pixsize, pixsize);
    for(int i = 0; i < 224; i++) {
        sd_font_decode(&sdfont, &img, i, 1);
        sur = vector_append_ptr(&font->surfaces);
        surface_create_from_vga(sur, &img);
        surface_set_transparency(sur, 0);
    }

    // Set font info vars
    font->w = pixsize;
    font->h = pixsize;
    font->size = size;

    // Free resources
    sd_vga_image_free(&img);
    sd_font_free(&sdfont);
    return 0;
}

static int pcx_font_load(font *font, const path *filename, int8_t palette_offset) {
    sd_vga_image img;
    pcx_font pcx_font;
    int pixsize;
    surface *sur;

    if(pcx_load_font(&pcx_font, filename)) {
        pcx_font_free(&pcx_font);
        return 1;
    }

    pixsize = pcx_font.glyph_height;

    // Load into textures
    for(int i = 0; i < pcx_font.glyph_count; i++) {
        sd_vga_image_create(&img, pcx_font.glyphs[i].width, pixsize);
        pcx_font_decode(&pcx_font, &img, i, 1);
        sur = vector_append_ptr(&font->surfaces);
        surface_create_from_vga(sur, &img);
        surface_set_transparency(sur, 0);
        sd_vga_image_free(&img);
    }

    // Set font info vars
    font->w = 0;
    font->h = pixsize;
    font->size = pixsize;

    // Free resources
    pcx_font_free(&pcx_font);
    return 0;
}

bool fonts_init(void) {
    path filename;
    font_create(&font_small);
    font_create(&font_large);
    font_create(&font_net1);
    font_create(&font_net2);

    // Load small font
    filename = get_resource_filename("CHARSMAL.DAT");
    if(font_load(&font_small, &filename, FONT_SMALL)) {
        log_error("Unable to load font file '%s'!", path_c(&filename));
        goto error_4;
    }
    log_info("Loaded font file '%s'", path_c(&filename));

    // Load big font
    filename = get_resource_filename("GRAPHCHR.DAT");
    if(font_load(&font_large, &filename, FONT_BIG)) {
        log_error("Unable to load font file '%s'!", path_c(&filename));
        goto error_3;
    }
    log_info("Loaded font file '%s'", path_c(&filename));

    // Load big net font
    filename = get_resource_filename("NETFONT1.PCX");
    if(pcx_font_load(&font_net1, &filename, 3)) {
        log_error("Unable to load font file '%s'!", path_c(&filename));
        goto error_2;
    }
    log_info("Loaded font file '%s'", path_c(&filename));

    // Load small net font
    filename = get_resource_filename("NETFONT2.PCX");
    if(pcx_font_load(&font_net2, &filename, 16)) {
        log_error("Unable to load font file '%s'!", path_c(&filename));
        goto error_1;
    }
    log_info("Loaded font file '%s'", path_c(&filename));

    // Hangul glyphs for the Korean translation (optional file)
    ko_load();
    if(ko_loaded) {
        font_small.ko = &ko_small;
        font_large.ko = &ko_big;
    }

    // All done.
    fonts_loaded = 1;
    return true;

error_1:
    font_free(&font_net2);
error_2:
    font_free(&font_net1);
error_3:
    font_free(&font_large);
error_4:
    font_free(&font_small);
    return false;
}

void fonts_set_font(font *new_font, font_size font_sz) {
    switch(font_sz) {
        case FONT_BIG:
            font_large = *new_font;
            break;
        case FONT_SMALL:
            font_small = *new_font;
            break;
        case FONT_NET1:
            font_net1 = *new_font;
            break;
        case FONT_NET2:
            font_net2 = *new_font;
            break;
        default:
            return;
    }
}

const font *fonts_get_font(font_size font) {
    switch(font) {
        case FONT_BIG:
            return &font_large;
        case FONT_SMALL:
            return &font_small;
        case FONT_NET1:
            return &font_net1;
        case FONT_NET2:
            return &font_net2;
        default:
            return NULL;
    }
}

void fonts_close(void) {
    if(fonts_loaded) {
        font_free(&font_small);
        font_free(&font_large);
        font_free(&font_net1);
        font_free(&font_net2);
        ko_free(&ko_small);
        ko_free(&ko_big);
        ko_loaded = false;
        fonts_loaded = 0;
    }
}
